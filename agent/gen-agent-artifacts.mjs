#!/usr/bin/env node
/**
 * Deterministic static-artifact generator for BitWave's agent layer.
 *
 * Writes the committed files described by docs/AGENT-INTERFACE.md §11:
 *
 *   agent/manifest.json                 byte-identical to getManifest()
 *   agent/examples/<tool>.json          one success envelope per pure tool
 *   agent/examples/README.md            generated index
 *
 * No timestamps, randomness or locale formatting: the same core always produces
 * the same bytes. `--check` recomputes in memory and exits 1 on stale/missing
 * files, so CI and the CLI `artifacts --check` command can gate commits.
 *
 * Usage: node agent/gen-agent-artifacts.mjs [--check] [--json]
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { TOOLS, callTool, getManifest } from "../src/core/agent-tools.ts";

const AGENT_DIR = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(AGENT_DIR, "..");

/** Filename of the manifest relative to the repository root. */
export const MANIFEST_FILE = "agent/manifest.json";
/** Directory of generated example envelopes relative to the repository root. */
export const EXAMPLES_DIR = "agent/examples";

const INDEX_FILE = `${EXAMPLES_DIR}/README.md`;

function renderExamplesIndex() {
  const lines = [
    "# BitWave agent examples",
    "",
    "Generated by `node agent/gen-agent-artifacts.mjs`; do not edit by hand.",
    "",
    "Every `.json` file is one complete success envelope returned by the tool's first",
    "documented example in `src/core/agent-tools.ts`, pretty-printed with two spaces.",
    "The envelopes are deterministic: no timestamps, no randomness, no locale output.",
    "Argument schemas live in `agent/manifest.json`.",
    "",
    "| file | tool | note |",
    "| --- | --- | --- |",
  ];
  for (const tool of TOOLS) {
    const example = tool.examples[0];
    if (!example) throw new Error(`tool ${tool.name} has no documented example`);
    const note = String(example.note).replace(/\|/g, "\\|");
    lines.push(`| [${tool.name}.json](${tool.name}.json) | \`${tool.name}\` | ${note} |`);
  }
  lines.push(
    "",
    "`examples/manifest.json` is the `manifest` tool envelope (its `data` is the",
    "capability manifest). One directory up, `agent/manifest.json` is the bare",
    "manifest object, byte-identical to `JSON.stringify(getManifest(), null, 2) + \"\\n\"`.",
    "",
  );
  return lines.join("\n");
}

/**
 * Recompute every generated artifact in memory. Insertion order is the write
 * order and therefore deterministic: manifest, tool envelopes in canonical
 * registry order, then the examples index.
 *
 * @returns {Map<string, string>} repo-relative path -> exact file content
 */
export function buildArtifacts() {
  const files = new Map();
  files.set(MANIFEST_FILE, JSON.stringify(getManifest(), null, 2) + "\n");
  for (const tool of TOOLS) {
    const example = tool.examples[0];
    if (!example) throw new Error(`tool ${tool.name} has no documented example`);
    const envelope = callTool(tool.name, structuredClone(example.args));
    files.set(`${EXAMPLES_DIR}/${tool.name}.json`, JSON.stringify(envelope, null, 2) + "\n");
  }
  files.set(INDEX_FILE, renderExamplesIndex());
  return files;
}

/**
 * Write every artifact. Idempotent: running twice leaves identical bytes.
 *
 * @param {string} [root] repository root (defaults to this checkout)
 */
export function generateArtifacts(root = REPO_ROOT) {
  const files = buildArtifacts();
  const written = [];
  for (const [relative, content] of files) {
    const absolute = path.join(root, relative);
    mkdirSync(path.dirname(absolute), { recursive: true });
    writeFileSync(absolute, content, "utf8");
    written.push(relative);
  }
  return { ok: true, mode: "generate", files: written, missing: [], stale: [] };
}

/**
 * Recompute in memory and compare byte-for-byte with the committed files.
 *
 * @param {string} [root] repository root (defaults to this checkout)
 */
export function checkArtifacts(root = REPO_ROOT) {
  const files = buildArtifacts();
  const missing = [];
  const stale = [];
  for (const [relative, content] of files) {
    const absolute = path.join(root, relative);
    if (!existsSync(absolute)) {
      missing.push(relative);
      continue;
    }
    if (!readFileSync(absolute).equals(Buffer.from(content, "utf8"))) stale.push(relative);
  }
  return { ok: missing.length === 0 && stale.length === 0, mode: "check", files: [...files.keys()], missing, stale };
}

/** True when this module is the process entry point (not imported by a test). */
export function isMainModule(moduleUrl) {
  const entry = process.argv[1];
  if (!entry) return false;
  const self = fileURLToPath(moduleUrl);
  const resolved = path.resolve(entry);
  return process.platform === "win32"
    ? self.toLowerCase() === resolved.toLowerCase()
    : self === resolved;
}

export function runGenerator(argv = process.argv.slice(2), io = process) {
  const args = argv.filter((argument) => !argument.startsWith("--") || argument === "--json" || argument === "--check");
  const json = args.includes("--json");
  const check = args.includes("--check");
  const unknown = args.filter((argument) => argument !== "--json" && argument !== "--check");
  if (unknown.length > 0) {
    io.stderr.write(`error: unknown argument: ${unknown[0]}\n`);
    return 2;
  }
  if (check) {
    const result = checkArtifacts();
    if (json) {
      io.stdout.write(JSON.stringify(result, null, 2) + "\n");
    } else if (result.ok) {
      io.stdout.write(`artifacts up to date (${result.files.length} files)\n`);
    } else {
      for (const file of result.missing) io.stdout.write(`missing: ${file}\n`);
      for (const file of result.stale) io.stdout.write(`stale: ${file}\n`);
      io.stderr.write("artifacts are out of date; run node agent/gen-agent-artifacts.mjs\n");
    }
    return result.ok ? 0 : 1;
  }
  const result = generateArtifacts();
  if (json) {
    io.stdout.write(JSON.stringify(result, null, 2) + "\n");
  } else {
    for (const file of result.files) io.stdout.write(`wrote ${file}\n`);
    io.stdout.write(`generated ${result.files.length} artifacts\n`);
  }
  return 0;
}

if (isMainModule(import.meta.url)) {
  process.exitCode = runGenerator();
}
